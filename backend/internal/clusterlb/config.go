// Package clusterlb generates the ingress configuration and defines which routes
// may run on a worker. Keep the proxy and application routing contract together.
package clusterlb

import (
	"encoding/json"
	"fmt"
	"io"
	"net/netip"
	"regexp"
	"strings"
)

// Stateful media/task, payment, plugin administration and all unknown routes
// deliberately fall back to the primary. Adding an API requires classification.
const GatewayPattern = `^(/v1)?/(messages(/count_tokens)?|chat/completions|embeddings|models(/[^/]+)?|usage|systemone|alpha/search|web_search|x_search|images/(generations|edits))$|^(/antigravity)?/v1beta/(models(/.*)?|cachedContents(/[^/]+)?)$|^/antigravity/(models|v1/(messages(/count_tokens)?|models|usage))$|^/backend-api/codex/(models|alpha/search)$`
const AffinityPattern = `^(/v1|/backend-api/codex)?/responses(/.*)?$`

var gatewayRE = regexp.MustCompile(GatewayPattern)
var affinityRE = regexp.MustCompile(AffinityPattern)
var nodeIDRE = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$`)

func WorkerPath(path string) bool { return gatewayRE.MatchString(path) || affinityRE.MatchString(path) }

type Node struct {
	ID             string `json:"id"`
	Address        string `json:"address"`
	Role           string `json:"role"`
	Weight         int    `json:"weight"`
	Disabled       bool   `json:"disabled,omitempty"`
	MaxConnections int    `json:"max_connections,omitempty"`
}

type Config struct {
	Listen string `json:"listen"`
	Nodes  []Node `json:"nodes"`
	// HA routes the management backend by the current leased role, not a fixed host.
	HA bool `json:"ha,omitempty"`
}

func Read(r io.Reader) (Config, error) {
	var cfg Config
	d := json.NewDecoder(io.LimitReader(r, 1024*1024))
	d.DisallowUnknownFields()
	if err := d.Decode(&cfg); err != nil {
		return cfg, err
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return cfg, fmt.Errorf("expected one JSON configuration object")
	}
	return cfg, cfg.Validate()
}

func (c Config) Validate() error {
	listen, err := netip.ParseAddrPort(c.Listen)
	if err != nil || !listen.Addr().IsLoopback() || listen.Port() == 0 {
		return fmt.Errorf("listen must be a loopback IP:port behind the local TLS reverse proxy")
	}
	if len(c.Nodes) < 2 || len(c.Nodes) > 100 {
		return fmt.Errorf("configure between 2 and 100 nodes")
	}
	ids, addresses := map[string]bool{}, map[netip.AddrPort]bool{}
	primaries, enabled := 0, 0
	for _, n := range c.Nodes {
		if !nodeIDRE.MatchString(n.ID) || ids[n.ID] {
			return fmt.Errorf("invalid or duplicate node id %q", n.ID)
		}
		ids[n.ID] = true
		addr, err := netip.ParseAddrPort(n.Address)
		if err != nil || addr.Port() == 0 || (!addr.Addr().IsPrivate() && !addr.Addr().IsLoopback()) || addresses[addr] || addr == listen {
			return fmt.Errorf("node %s requires a unique private tunnel IP:port (or loopback for local tests)", n.ID)
		}
		addresses[addr] = true
		if n.Weight < 1 || n.Weight > 256 {
			return fmt.Errorf("node %s weight must be 1-256", n.ID)
		}
		if n.MaxConnections < 0 || n.MaxConnections > 20000 {
			return fmt.Errorf("node %s max_connections must be 0-20000", n.ID)
		}
		if n.Role != "primary" && n.Role != "worker" && (!c.HA || n.Role != "candidate") {
			return fmt.Errorf("node %s role must be primary or worker", n.ID)
		}
		if c.HA && n.Role != "candidate" {
			return fmt.Errorf("HA inventory nodes must all use role candidate")
		}
		if n.Role == "primary" {
			primaries++
			if n.Disabled {
				return fmt.Errorf("primary cannot be disabled; promote a prepared replacement first")
			}
		}
		if !n.Disabled {
			enabled++
		}
	}
	if (!c.HA && primaries != 1) || enabled == 0 {
		return fmt.Errorf("exactly one enabled primary is required")
	}
	return nil
}

func (c Config) Render() (string, error) {
	if err := c.Validate(); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by sub2api cluster-config; HAProxy 3.2+.
# TLS/client-IP sanitization happens at the local Nginx. Never expose this bind.
global
    maxconn 20000
    tune.bufsize 131072
defaults
    mode http
    timeout connect 5s
    timeout client 1800s
    timeout server 1800s
    timeout tunnel 3600s
    timeout http-request 30s
    timeout http-keep-alive 60s
    timeout check 3s
    timeout queue 10s
    retries 0
frontend sub2api
    bind %s
    http-request deny deny_status 404 if { path -i /readyz }
    # External ingress is ready only when management and inference can route.
    http-request return status 200 content-type text/plain string ready if { path -i /ingress-ready } { nbsrv(primary) gt 0 } { nbsrv(gateway) gt 0 } { nbsrv(responses) gt 0 }
    http-request return status 503 content-type text/plain string unavailable if { path -i /ingress-ready }
    http-request del-header X-Sub2API-Node
    http-request del-header X-Sub2API-Affinity
    http-request del-header CF-Connecting-IP
    # Extract credentials only into a transaction variable, never a log/header.
    http-request set-var(txn.affinity) req.hdr(x-goog-api-key)
    http-request set-var(txn.affinity) req.hdr(x-api-key) if { req.hdr(x-api-key) -m found }
    http-request set-var(txn.affinity) req.hdr(authorization),regsub(^[^[:space:]]+[[:space:]]+,,),regsub([[:space:]]+$,,) if { req.hdr(authorization) -m beg -i "Bearer " }
    # Scope affinity to a stable conversation when the client provides one.
    # Credentials remain part of the key, isolating identical session IDs.
    http-request set-var(txn.session) req.hdr(session_id)
    http-request set-var(txn.session) req.hdr(conversation_id) if { req.hdr(conversation_id) -m found }
    http-request set-var(txn.session) req.hdr(X-Sub2API-Session-ID) if { req.hdr(X-Sub2API-Session-ID) -m found }
    http-request set-var-fmt(txn.affinity) "%%[var(txn.affinity)]|%%[var(txn.session)]" if { var(txn.session) -m len 1:256 }
    acl affinity_route path_reg %s
    acl gateway_route path_reg %s
    use_backend responses if affinity_route
    use_backend gateway if gateway_route
    default_backend primary
`, c.Listen, AffinityPattern, GatewayPattern)
	for _, backend := range []string{"primary", "gateway", "responses"} {
		fmt.Fprintf(&b, "\nbackend %s\n", backend)
		if backend == "responses" {
			_, _ = b.WriteString("    balance hash var(txn.affinity)\n    hash-type consistent\n")
		} else {
			_, _ = b.WriteString("    balance leastconn\n")
		}
		_, _ = b.WriteString("    option httpchk\n    http-check connect\n")
		// Per-server readiness verifies the node ID. The dedicated primary
		// backend additionally checks role to catch an accidental demotion.
		role := ""
		if backend == "primary" {
			role = "&role=primary"
		}
		fmt.Fprintf(&b, "    http-check send meth GET uri-lf /readyz?node=%%[srv_name]%s ver HTTP/1.1 hdr Host localhost\n", role)
		_, _ = b.WriteString("    http-check expect status 200\n    http-check expect string '\"status\":\"ready\"'\n    default-server check inter 2s fall 2 rise 2\n")
		for _, n := range c.Nodes {
			if backend == "primary" && n.Role != "primary" && !c.HA {
				continue
			}
			disabled := ""
			if n.Disabled {
				disabled = " disabled"
			}
			limit := ""
			if n.MaxConnections > 0 {
				limit = fmt.Sprintf(" maxconn %d maxqueue %d", n.MaxConnections, n.MaxConnections)
			}
			fmt.Fprintf(&b, "    server %s %s weight %d%s%s\n", n.ID, n.Address, n.Weight, disabled, limit)
		}
	}
	return b.String(), nil
}
