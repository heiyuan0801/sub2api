CREATE TABLE docs_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    position INTEGER NOT NULL CHECK (position >= 0)
);

CREATE TABLE docs_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES docs_categories(id),
    slug VARCHAR(96) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(320) NOT NULL DEFAULT '',
    markdown TEXT NOT NULL DEFAULT '',
    seo_title VARCHAR(160) NOT NULL DEFAULT '',
    seo_description VARCHAR(320) NOT NULL DEFAULT '',
    visibility TEXT NOT NULL DEFAULT 'public' CHECK (visibility IN ('public', 'authenticated')),
    position INTEGER NOT NULL CHECK (position >= 0),
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'offline')),
    revision BIGINT NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Serving a draft never reads the editable article fields. Publishing swaps the
-- whole snapshot, including its audience and attachments, in one transaction.
CREATE TABLE docs_publications (
    article_id BIGINT PRIMARY KEY REFERENCES docs_articles(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES docs_categories(id),
    slug VARCHAR(96) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(320) NOT NULL,
    markdown TEXT NOT NULL,
    seo_title VARCHAR(160) NOT NULL,
    seo_description VARCHAR(320) NOT NULL,
    visibility TEXT NOT NULL CHECK (visibility IN ('public', 'authenticated')),
    revision BIGINT NOT NULL,
    position INTEGER NOT NULL CHECK (position >= 0),
    published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('simple'::regconfig, title), 'A') ||
        setweight(to_tsvector('simple'::regconfig, description), 'B') ||
        to_tsvector('simple'::regconfig, markdown)
    ) STORED
);

CREATE INDEX docs_publications_search ON docs_publications USING GIN (search_vector);
CREATE INDEX docs_articles_category_order ON docs_articles(category_id, position, id);
CREATE INDEX docs_publications_category ON docs_publications(category_id);

CREATE TABLE docs_images (
    id UUID PRIMARY KEY,
    article_id BIGINT NOT NULL REFERENCES docs_articles(id) ON DELETE CASCADE,
    content_type TEXT NOT NULL CHECK (content_type IN ('image/png', 'image/jpeg', 'image/gif', 'image/webp')),
    data BYTEA,
    object_key TEXT,
    CHECK ((data IS NULL) <> (object_key IS NULL)),
    UNIQUE(article_id, id)
);

CREATE TABLE docs_publication_images (
    article_id BIGINT NOT NULL REFERENCES docs_publications(article_id) ON DELETE CASCADE,
    image_id UUID NOT NULL,
    PRIMARY KEY (article_id, image_id),
    FOREIGN KEY (article_id, image_id) REFERENCES docs_images(article_id, id) ON DELETE CASCADE
);

